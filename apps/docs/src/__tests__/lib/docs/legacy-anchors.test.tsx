import { render } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
  LEGACY_HOP_KEY,
  followLegacyAnchor,
  hashId,
  legacyTarget,
  localeOf,
  pagePath,
  type LegacyAnchorEnv,
  type LegacyAnchorMap,
} from "@/lib/docs/legacy-anchors";

const MAP: LegacyAnchorMap = {
  _generated: "GENERATED by packages/docs-tooling/src/generators/…",
  "/developers/docs/quickstart": {
    "install-the-solana-cli":
      "/developers/docs/intro/installation/dependencies#install-solana-cli",
    "quick-start": "#follow-along-locally",
    "token-cli-examples": "/developers/docs/references/spl-token-cli",
  },
  "/ja/developers/docs/core/accounts": {
    アカウント: "#accounts",
    "ネイティブc#": "/ja/developers/docs/clients/community/game-sdks#native-c#",
  },
};

/** A page with these element ids, at `url`. */
function env(url: string, ids: string[], map: LegacyAnchorMap | null = MAP) {
  let current = new URL(url, "https://solana.com");
  const elements = new Map(
    ids.map((id) => [id, { id, scrollIntoView: vi.fn() }]),
  );
  const store = new Map<string, string>();
  const e = {
    location: {
      get pathname() {
        return current.pathname;
      },
      get search() {
        return current.search;
      },
      get hash() {
        return current.hash;
      },
      get href() {
        return current.href;
      },
      replace: vi.fn((to: string) => {
        current = new URL(to, current);
      }),
    },
    document: {
      getElementById: (id: string) =>
        (elements.get(id) as unknown as HTMLElement) ?? null,
    },
    history: {
      state: { __NA: true },
      replaceState: vi.fn((_state: unknown, _title: string, to: string) => {
        current = new URL(to, current);
      }),
    },
    load: vi.fn(async () => map),
    storage: {
      getItem: (k: string) => store.get(k) ?? null,
      setItem: (k: string, v: string) => void store.set(k, v),
      removeItem: (k: string) => void store.delete(k),
    },
  } satisfies LegacyAnchorEnv;
  return { ...e, elements, store, url: () => current.href };
}

describe("legacy anchors: helpers", () => {
  it("decodes the hash", () => {
    expect(hashId("#a-b")).toBe("a-b");
    expect(hashId("#%E3%82%A2")).toBe("ア");
    expect(hashId("#100%")).toBe("100%");
    expect(hashId("#")).toBeNull();
    expect(hashId("")).toBeNull();
  });

  it("keys pages by their public path", () => {
    expect(localeOf("/ja/developers/docs/core")).toBe("ja");
    expect(localeOf("/developers/docs/core")).toBe("en");
    expect(localeOf("/en/developers/docs/core")).toBe("en");
    expect(pagePath("/developers/docs/quickstart/")).toBe(
      "/developers/docs/quickstart",
    );
    expect(pagePath("/en/developers/docs/quickstart")).toBe(
      "/developers/docs/quickstart",
    );
    expect(
      legacyTarget(MAP, "/developers/docs/quickstart", "quick-start"),
    ).toBe("#follow-along-locally");
    expect(legacyTarget(MAP, "/developers/docs/quickstart", "nope")).toBeNull();
    expect(legacyTarget(MAP, "/_generated", "x")).toBeNull();
    expect(legacyTarget(null, "/developers/docs/quickstart", "x")).toBeNull();
  });
});

describe("legacy anchors: followLegacyAnchor", () => {
  it("moves an unmatched hash to its section on another page", async () => {
    const e = env("/developers/docs/quickstart#install-the-solana-cli", [
      "follow-along-locally",
    ]);
    expect(await followLegacyAnchor(e)).toBe("navigated");
    expect(e.load).toHaveBeenCalledWith("en");
    expect(e.location.replace).toHaveBeenCalledWith(
      "/developers/docs/intro/installation/dependencies#install-solana-cli",
    );
    expect(e.store.get(LEGACY_HOP_KEY)).toBe(
      "/developers/docs/intro/installation/dependencies#install-solana-cli",
    );
  });

  it("goes to the top of a page when the target has no id", async () => {
    const e = env("/developers/docs/quickstart#token-cli-examples", []);
    expect(await followLegacyAnchor(e)).toBe("navigated");
    expect(e.location.replace).toHaveBeenCalledWith(
      "/developers/docs/references/spl-token-cli",
    );
  });

  it("scrolls on the same page, replacing the hash and keeping the router state", async () => {
    const e = env("/developers/docs/quickstart?x=1#quick-start", [
      "follow-along-locally",
    ]);
    expect(await followLegacyAnchor(e)).toBe("scrolled");
    expect(e.history.replaceState).toHaveBeenCalledWith(
      { __NA: true },
      "",
      "/developers/docs/quickstart?x=1#follow-along-locally",
    );
    expect(
      e.elements.get("follow-along-locally")!.scrollIntoView,
    ).toHaveBeenCalled();
    expect(e.location.replace).not.toHaveBeenCalled();
  });

  it("leaves a hash the page has alone, without loading the map", async () => {
    const e = env("/developers/docs/quickstart#quick-start", ["quick-start"]);
    expect(await followLegacyAnchor(e)).toBe("none");
    expect(e.load).not.toHaveBeenCalled();
    expect(e.url()).toBe(
      "https://solana.com/developers/docs/quickstart#quick-start",
    );
  });

  it("does nothing without a hash, for #top, or for an anchor not in the map", async () => {
    for (const url of [
      "/developers/docs/quickstart",
      "/developers/docs/quickstart#top",
      "/developers/docs/quickstart#something-else",
      "/developers/docs/unknown#quick-start",
    ]) {
      const e = env(url, []);
      expect(await followLegacyAnchor(e), url).toBe("none");
      expect(e.location.replace).not.toHaveBeenCalled();
      expect(e.history.replaceState).not.toHaveBeenCalled();
    }
  });

  it("does nothing when the map can't be loaded", async () => {
    const e = env("/developers/docs/quickstart#quick-start", [], null);
    expect(await followLegacyAnchor(e)).toBe("none");
  });

  it("works on locale paths, with percent-encoded anchors", async () => {
    const e = env(
      `/ja/developers/docs/core/accounts#${encodeURIComponent("アカウント")}`,
      ["accounts"],
    );
    expect(await followLegacyAnchor(e)).toBe("scrolled");
    expect(e.load).toHaveBeenCalledWith("ja");
    expect(e.url()).toBe(
      "https://solana.com/ja/developers/docs/core/accounts#accounts",
    );

    const other = env(
      `/ja/developers/docs/core/accounts#${encodeURIComponent("ネイティブc#")}`,
      [],
    );
    expect(await followLegacyAnchor(other)).toBe("navigated");
    // The target id is encoded, so its own "#" survives.
    expect(other.location.replace).toHaveBeenCalledWith(
      "/ja/developers/docs/clients/community/game-sdks#native-c%23",
    );
  });

  it("does not loop: after a move, the next page never moves again", async () => {
    // A stale map: the target section is missing on the page moved to, and
    // the map has an entry for it there.
    const map: LegacyAnchorMap = {
      "/developers/docs/a": { old: "/developers/docs/b#gone" },
      "/developers/docs/b": { gone: "/developers/docs/a#old" },
    };
    const first = env("/developers/docs/a#old", [], map);
    expect(await followLegacyAnchor(first)).toBe("navigated");
    const second = env("/developers/docs/b#gone", [], map);
    second.store.set(LEGACY_HOP_KEY, first.store.get(LEGACY_HOP_KEY)!);
    expect(await followLegacyAnchor(second)).toBe("none");
    expect(second.location.replace).not.toHaveBeenCalled();
    expect(second.store.has(LEGACY_HOP_KEY)).toBe(false);
  });

  it("does not move when the same-page target is missing or is the hash itself", async () => {
    const missing = env("/developers/docs/quickstart#quick-start", []);
    expect(await followLegacyAnchor(missing)).toBe("none");
    const self = env("/developers/docs/x#a", ["b"], {
      "/developers/docs/x": { a: "#a" },
    });
    expect(await followLegacyAnchor(self)).toBe("none");
    expect(self.history.replaceState).not.toHaveBeenCalled();
  });

  it("does nothing if the reader moved on while the map loaded", async () => {
    const e = env("/developers/docs/quickstart#quick-start", [
      "follow-along-locally",
    ]);
    e.load.mockImplementation(async () => {
      e.location.replace("/developers/docs/quickstart#elsewhere");
      e.location.replace.mockClear();
      return MAP;
    });
    expect(await followLegacyAnchor(e)).toBe("none");
    expect(e.history.replaceState).not.toHaveBeenCalled();
  });
});

describe("LegacyAnchors component", () => {
  const fetchMock = vi.fn();
  beforeEach(() => {
    vi.resetModules();
    fetchMock.mockReset();
    vi.stubGlobal("fetch", fetchMock);
    vi.doMock("next/navigation", () => ({
      usePathname: () => window.location.pathname,
    }));
  });
  afterEach(() => {
    vi.unstubAllGlobals();
    vi.doUnmock("next/navigation");
    window.history.replaceState(null, "", "/");
    document.body.innerHTML = "";
  });

  async function mount() {
    const { LegacyAnchors } =
      await import("@/components/docs/legacy-anchors.client");
    return render(<LegacyAnchors />);
  }

  it("fetches the locale's map only for a hash that matches nothing", async () => {
    window.history.replaceState(null, "", "/ja/developers/docs/x#old");
    document.body.innerHTML = `<h2 id="new">New</h2>`;
    const scroll = vi.fn();
    document.getElementById("new")!.scrollIntoView = scroll;
    fetchMock.mockResolvedValue({
      ok: true,
      json: async () => ({ "/ja/developers/docs/x": { old: "#new" } }),
    });
    await mount();
    await vi.waitFor(() => expect(window.location.hash).toBe("#new"));
    expect(fetchMock).toHaveBeenCalledWith(
      "/docs-assets/legacy-anchors/ja.json",
    );
    expect(scroll).toHaveBeenCalled();
  });

  it("never fetches for a hash the page has", async () => {
    window.history.replaceState(null, "", "/developers/docs/x#here");
    document.body.innerHTML = `<h2 id="here">Here</h2>`;
    await mount();
    window.dispatchEvent(new HashChangeEvent("hashchange"));
    await new Promise((r) => setTimeout(r, 0));
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("follows a hash change to an old anchor", async () => {
    window.history.replaceState(null, "", "/developers/docs/x");
    document.body.innerHTML = `<h2 id="new">New</h2>`;
    document.getElementById("new")!.scrollIntoView = vi.fn();
    fetchMock.mockResolvedValue({
      ok: true,
      json: async () => ({ "/developers/docs/x": { old: "#new" } }),
    });
    await mount();
    expect(fetchMock).not.toHaveBeenCalled();
    window.history.replaceState(null, "", "/developers/docs/x#old");
    window.dispatchEvent(new HashChangeEvent("hashchange"));
    await vi.waitFor(() => expect(window.location.hash).toBe("#new"));
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });
});
