/*
 * Playground buttons (styles/playground.css).
 *
 * The docs app loads this script on every docs page
 * (components/docs/docs-scripts.tsx). A tutorial has at most one Playground
 * button, in a block at the top of its intro page; code blocks, demo
 * terminals, and step pages have none. There are two kinds:
 *
 * - "Open tutorial in Playground", for program tutorials (Anchor/Native):
 *   `<a class="sol-pg-tut" data-pg-open="packages/docs-examples/…">`,
 *   data-pg-open being the folder to import. Single-page tutorials (e.g.
 *   /developers/docs/programs/build-first-program) write it by hand;
 *   docs-tooling gen:paths generates it
 *   (snippets/paths/<lang>/<key>/playground.mdx) for a job tutorial whose
 *   example folder is a program. This script makes it a link (new tab) to
 *   <CONFIG.origin>/github.com/<CONFIG.source>/<data-pg-open>. The
 *   playground then reads the files through the GitHub contents API
 *   (unauthenticated: 60 requests per hour per reader IP, one request per
 *   imported folder).
 * - "Run in Playground", for TypeScript tutorials whose example folder has a
 *   playground.ts: `<a class="sol-pg-tut" data-pg-run href="…/open#v=1&…">`,
 *   generated by gen:paths with the file in the link (`code`), so it works
 *   without JavaScript too. This script points it at CONFIG.runOrigin and
 *   sets `from` to the page the reader is on (CONFIG.site + its path, locale
 *   prefix included), the page Playground links back to.
 */
(function () {
  if (window.__solPlayground) return;
  window.__solPlayground = true;

  var CONFIG = {
    // Program tutorials: Solana Playground's GitHub import.
    origin: "https://beta.solpg.io",
    // THE one value for owner/repo/ref the playground imports from.
    // The ref may not contain "/" (the playground's URL parser stops
    // there). Never prefix "https://": the playground's router collapses
    // "//" and then rejects the URL ("URL path not found").
    source: "solana-foundation/solana-com/tree/main",
    // TypeScript tutorials: THE origin of the Playground that opens one file
    // from a link (/open#…). Temporary host: it becomes
    // https://playground.solana.com once that is live. gen:paths reads this
    // line for the links it generates, so run it after a change.
    runOrigin: "https://solana-playground-teal.vercel.app",
    // Playground only links back to https pages on solana.com.
    site: "https://solana.com",
  };
  var SAFE_PATH = /^[\w\-/.]+$/;

  function apply(btn) {
    var open = btn.getAttribute("data-pg-open") || "";
    if (!SAFE_PATH.test(open) || open.indexOf("..") !== -1) return;
    var href = CONFIG.origin + "/github.com/" + CONFIG.source + "/" + open;
    if (btn.getAttribute("href") === href) return;
    btn.setAttribute("href", href);
    btn.setAttribute("target", "_blank");
    btn.setAttribute("rel", "noopener noreferrer");
    btn.setAttribute(
      "aria-label",
      btn.textContent.trim() + " (opens in a new tab)",
    );
  }

  // The generated link already opens in a new tab and names that in its
  // text (a visually hidden span), so only the origin and `from` change.
  function applyRun(link) {
    var hash = (link.getAttribute("href") || "").split("#")[1];
    if (!hash) return;
    var params = new URLSearchParams(hash);
    if (!params.get("code")) return;
    params.set("from", CONFIG.site + location.pathname.replace(/\/+$/, ""));
    var href = CONFIG.runOrigin + "/open#" + params.toString();
    if (link.getAttribute("href") !== href) link.setAttribute("href", href);
  }

  function scan() {
    var btns = document.querySelectorAll(".sol-pg-tut");
    for (var i = 0; i < btns.length; i++)
      if (btns[i].hasAttribute("data-pg-run")) applyRun(btns[i]);
      else apply(btns[i]);
  }

  // The docs navigate client-side, so new pages arrive as DOM mutations.
  var pending = false;
  function schedule() {
    if (pending) return;
    pending = true;
    setTimeout(function () {
      pending = false;
      scan();
    }, 60);
  }
  if (typeof MutationObserver === "function")
    new MutationObserver(schedule).observe(document.documentElement, {
      childList: true,
      subtree: true,
    });
  if (document.readyState === "loading")
    document.addEventListener("DOMContentLoaded", schedule);
  else schedule();

  // A click before the next scan still opens the playground.
  document.addEventListener(
    "click",
    function (event) {
      var btn = event.target.closest && event.target.closest(".sol-pg-tut");
      if (!btn) return;
      if (btn.hasAttribute("data-pg-run")) applyRun(btn);
      else apply(btn);
    },
    true,
  );
})();
