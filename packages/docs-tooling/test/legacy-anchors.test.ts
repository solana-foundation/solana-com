/**
 * gen:legacy-anchors against a throwaway docs root (ids come from the docs
 * app's own heading plugins, through src/lib/page-ids.ts).
 */
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  hubIds,
  parseSource,
  runLegacyAnchors,
} from "../src/generators/legacy-anchors.ts";
import { pageIds } from "../src/lib/page-ids.ts";
import type { Problem } from "../src/generators/_lib.ts";

let root: string;
let out: string;

const write = (rel: string, text: string) => {
  const abs = path.join(root, rel);
  mkdirSync(path.dirname(abs), { recursive: true });
  writeFileSync(abs, text);
};
const source = (locale: string, data: unknown) =>
  write(`legacy-anchors/${locale}.json`, JSON.stringify(data, null, 2));
const output = (locale: string) =>
  JSON.parse(readFileSync(path.join(out, `${locale}.json`), "utf8"));
const run = (check = false) =>
  runLegacyAnchors({
    docsRoot: root,
    outDir: out,
    hubFile: path.join(root, "no-hub.tsx"),
    check,
  });
const errors = (r: { problems: Problem[] }) =>
  r.problems.filter((p) => p.level === "error").map((p) => p.message);
const warnings = (r: { problems: Problem[] }) =>
  r.problems.filter((p) => p.level === "warn").map((p) => p.message);

beforeEach(() => {
  root = mkdtempSync(path.join(os.tmpdir(), "legacy-anchors-"));
  out = path.join(root, "out");
  write("docs/en/a.mdx", "---\ntitle: A\n---\n\n## First\n\n## Second\n");
  write(
    "docs/en/b.mdx",
    "---\ntitle: B\nanchorAliases:\n  renamed-kept: kept\n---\n\n## Kept\n\n### Other\n",
  );
  // A translation with the English headings' shape, and one without it.
  write("docs/ja/b.mdx", "---\ntitle: B\n---\n\n## 保持\n\n### その他\n");
  write("docs/ko/b.mdx", "---\ntitle: B\n---\n\n## 하나\n");
  write("cookbook/c.mdx", "---\ntitle: C\n---\n\n## Cook\n");
});

afterEach(() => rmSync(root, { recursive: true, force: true }));

describe("pageIds", () => {
  it("lists headings, steps and aliases as the docs app renders them", async () => {
    write(
      "docs/en/ids.mdx",
      [
        "---",
        "anchorAliases:",
        "  old-step: set-it-up",
        "---",
        "",
        "## Fees & Compute",
        "",
        "## Output",
        "",
        "## Output",
        "",
        "## surfnet\\_setAccount [#surfnet_setAccount]",
        "",
        "<Steps>",
        '  <Step title="Set it up">Text.</Step>',
        "</Steps>",
        "",
        '<div id="custom-box" />',
      ].join("\n"),
    );
    expect(await pageIds(path.join(root, "docs/en/ids.mdx"))).toEqual([
      { id: "fees-&-compute", kind: "heading", level: 2 },
      { id: "fees--compute", kind: "alias", of: "fees-&-compute" },
      { id: "output", kind: "heading", level: 2 },
      { id: "output-1", kind: "heading", level: 2 },
      { id: "surfnet_setAccount", kind: "heading", level: 2 },
      { id: "surfnet_setaccount", kind: "alias", of: "surfnet_setAccount" },
      { id: "set-it-up", kind: "step" },
      { id: "old-step", kind: "alias", of: "set-it-up" },
      { id: "custom-box", kind: "element" },
    ]);
  });
});

describe("gen:legacy-anchors", () => {
  it("writes each locale's map with public paths, placing ids on translations", async () => {
    source("en", {
      "/developers/docs/a": {
        "old-second": "#second",
        moved: "/developers/docs/b#other",
        "to-alias": "/developers/docs/b#renamed-kept",
        "to-top": "/developers/cookbook/c",
      },
    });
    source("ja", {
      "/developers/docs/a": { 移動: "/developers/docs/b#other" },
      "/developers/docs/b": { 古い: "#kept" },
      "/developers/cookbook/c": { 料理: "#cook" },
    });
    const r = await run();
    expect(errors(r)).toEqual([]);
    expect(r.written).toEqual(["out/en.json", "out/ja.json"]);
    expect(output("en")).toEqual({
      _generated: expect.stringContaining("GENERATED by"),
      "/developers/docs/a": {
        moved: "/developers/docs/b#other",
        "old-second": "#second",
        "to-alias": "/developers/docs/b#renamed-kept",
        "to-top": "/developers/cookbook/c",
      },
    });
    expect(output("ja")).toEqual({
      _generated: expect.stringContaining("legacy-anchors/ja.json"),
      // English page served at the locale URL: its English ids.
      "/ja/developers/cookbook/c": { 料理: "#cook" },
      // The translated page: the heading at the English one's position.
      "/ja/developers/docs/a": { 移動: "/ja/developers/docs/b#その他" },
      "/ja/developers/docs/b": { 古い: "#保持" },
    });
  });

  it("--check passes when the output is current and fails when it is stale", async () => {
    source("en", { "/developers/docs/a": { old: "#second" } });
    expect((await run()).ok).toBe(true);
    const clean = await run(true);
    expect(clean.ok).toBe(true);
    expect(clean.written).toEqual([]);

    source("en", { "/developers/docs/a": { old: "#first" } });
    const stale = await run(true);
    expect(stale.ok).toBe(false);
    expect(stale.written).toHaveLength(1);
    // --check never writes.
    expect(output("en")["/developers/docs/a"]).toEqual({ old: "#second" });

    // A locale whose source is gone: its output is an orphan.
    source("en", { "/developers/docs/a": { old: "#second" } });
    writeFileSync(
      path.join(out, "fr.json"),
      '{"_generated":"GENERATED by packages/docs-tooling/src/generators/legacy-anchors.ts"}\n',
    );
    const orphan = await run(true);
    expect(orphan.ok).toBe(false);
    expect(orphan.removed).toHaveLength(1);
    expect((await run()).ok).toBe(true);
    expect(existsSync(path.join(out, "fr.json"))).toBe(false);
  });

  it("fails on a target id the page doesn't have, and names the fix", async () => {
    source("en", {
      "/developers/docs/a": { old: "/developers/docs/b#renamed" },
    });
    const r = await run(true);
    expect(r.ok).toBe(false);
    expect(errors(r)).toEqual([
      expect.stringContaining("/developers/docs/b has no #renamed"),
    ]);
    expect(errors(r)[0]).toContain("anchorAliases");
  });

  it("fails on missing pages, locale prefixes, unknown locales and entries that go nowhere", async () => {
    source("en", {
      "/developers/docs/gone": { old: "#first" },
      "/ja/developers/docs/a": { old: "#first" },
      "/developers/docs/a": {
        "to-missing": "/developers/docs/missing",
        "own-top": "/developers/docs/a",
        self: "#self",
        "#hash": "#first",
        bad: "first",
      },
    });
    source("xx", {});
    const r = await run(true);
    expect(r.ok).toBe(false);
    const e = errors(r).join("\n");
    expect(e).toContain('"xx" is not a docs locale');
    expect(e).toContain("/developers/docs/gone: no such page");
    expect(e).toContain("/ja/developers/docs/a: pages are /developers paths");
    expect(e).toContain("target page /developers/docs/missing does not exist");
    expect(e).toContain("/developers/docs/a#own-top: an entry must lead");
    expect(e).toContain("/developers/docs/a#self: an entry must lead");
    expect(e).toContain('"#hash" must be the anchor without "#"');
    expect(e).toContain('/developers/docs/a#bad: target must be "#id"');
    // Nothing is written while there are errors.
    expect(existsSync(out)).toBe(false);
  });

  it("warns, and goes to the page top, when a translation's headings don't line up", async () => {
    source("ko", {
      "/developers/docs/a": { 이동: "/developers/docs/b#other" },
      "/developers/docs/b": { 옛: "#other" },
    });
    const r = await run();
    expect(errors(r)).toEqual([]);
    expect(warnings(r)).toHaveLength(2);
    expect(output("ko")).toEqual({
      _generated: expect.any(String),
      "/ko/developers/docs/a": { 이동: "/ko/developers/docs/b" },
    });
  });

  it("reports an entry for an id the page has again, and keeps it", async () => {
    source("en", { "/developers/docs/a": { first: "#second" } });
    const r = await run();
    expect(r.ok).toBe(true);
    expect(warnings(r)).toEqual([
      expect.stringContaining("the page has #first again"),
    ]);
    expect(output("en")["/developers/docs/a"]).toEqual({ first: "#second" });
  });

  it("parses the /developers landing's ids and old-id aliases", () => {
    expect(
      hubIds(
        '<section id="learn"><SectionHead\n  id="dl-routes-title"\n  aliases={["paths-heading", "learning-heading"]}\n/>',
      ),
    ).toEqual([
      { id: "learn", kind: "element" },
      { id: "dl-routes-title", kind: "element" },
      { id: "paths-heading", kind: "alias", of: "dl-routes-title" },
      { id: "learning-heading", kind: "alias", of: "dl-routes-title" },
    ]);
  });

  it("checks the source's shape", () => {
    const problems: Problem[] = [];
    expect(parseSource([], "x.json", problems)).toEqual({});
    expect(
      parseSource(
        { "/developers/docs/a": { ok: "#b", bad: 3 } },
        "x.json",
        problems,
      ),
    ).toEqual({ "/developers/docs/a": { ok: "#b" } });
    expect(problems.map((p) => p.message)).toEqual([
      "must be an object of page -> { old anchor: target }",
      expect.stringContaining("/developers/docs/a#bad: target must be"),
    ]);
  });
});
